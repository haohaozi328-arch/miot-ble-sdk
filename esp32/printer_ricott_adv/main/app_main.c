static os_membuf_t s_coc_mem[OS_MEMPOOL_SIZE(COC_BUF_COUNT, COC_SDU_MTU)];
static struct os_mempool  s_coc_pool;
static struct os_mbuf_pool s_coc_mbuf_pool;
static uint32_t s_coc_rx_bytes;
static uint8_t  s_coc_rx_seq;   /* 手机发来的帧序号，用来回放真机 ACK */

static int coc_event_cb(struct ble_l2cap_event *event, void *arg);

static struct os_mbuf *coc_alloc_sdu(void)
{
    return os_mbuf_get_pkthdr(&s_coc_mbuf_pool, 0);
}
static void coc_recv_ready(struct ble_l2cap_chan *chan)
{
    struct os_mbuf *m = coc_alloc_sdu();
    if (m) ble_l2cap_recv_ready(chan, m);
}
static int coc_event_cb(struct ble_l2cap_event *event, void *arg)
{
    (void)arg;
    switch (event->type) {
    case BLE_L2CAP_EVENT_COC_CONNECTED:
        ESP_LOGI(TAG, "L2CAP COC connected status=%d conn=%u",
                 event->connect.status, event->connect.conn_handle);
        if (event->connect.status == 0) {
            s_coc_chan = event->connect.chan;
            s_coc_rx_seq = 0;
            coc_recv_ready(s_coc_chan);
            /* ★先发 hello（501B, cmd=0x0409 flag=1）：真机时序，不发手机就等 10s 断开 */
            struct os_mbuf *tx = coc_alloc_sdu();
            if (tx && os_mbuf_append(tx, s_coc_hello, sizeof(s_coc_hello)) == 0) {
                int rc = ble_l2cap_send(s_coc_chan, tx);
                ESP_LOGI(TAG, "L2CAP TX hello %uB rc=%d",
                         (unsigned)sizeof(s_coc_hello), rc);
                if (rc) os_mbuf_free_chain(tx);
            } else if (tx) {
                os_mbuf_free_chain(tx);
            }
        }
        break;
    case BLE_L2CAP_EVENT_COC_DATA_RECEIVED: {
        struct os_mbuf *m = event->receive.sdu_rx;
        if (m) {
            s_coc_rx_bytes += m->om_len;
            /* 真机是严格 request-response：手机每发一帧，设备必须回一帧，否则
             * 手机重发几次后 8s 超时断开。手机第一帧是 hello（220B），不回；
             * 之后依次回放真机的 dev1/dev2/dev3 ACK。 */
            bool is_hello = (m->om_len >= 4 && m->om_data[2] == 0x55 && m->om_data[3] == 0xaa &&
                             m->om_data[10] == 0x09 && m->om_data[11] == 0x04);
            ESP_LOGI(TAG, "L2CAP RX %uB total=%lu seq=%u head=%02X %02X %02X %02X",
                     m->om_len, (unsigned long)s_coc_rx_bytes, s_coc_rx_seq,
                     m->om_data[0], m->om_data[1], m->om_data[2], m->om_data[3]);
            os_mbuf_free(m);

            if (!is_hello && s_coc_rx_seq < 4) {
                const uint8_t *ack; size_t ack_len;
                switch (s_coc_rx_seq) {
                case 0: ack = s_coc_dev_1; ack_len = sizeof(s_coc_dev_1); break;
                case 1: ack = s_coc_dev_2; ack_len = sizeof(s_coc_dev_2); break;
                case 2: ack = s_coc_dev_3; ack_len = sizeof(s_coc_dev_3); break;
                /* ★第4帧回 3950B 的 0x0429 大数据帧：真机在这一步之后手机才下发
                 * 3922B 的图片数据块（黄金样本 D4→P5）。这是能否拿到图片的关键。 */
                default: ack = s_coc_dev_4; ack_len = sizeof(s_coc_dev_4); break;
                }
                struct os_mbuf *tx = coc_alloc_sdu();
                if (tx) {
                    bool append_ok = true;
                    /* 大数据帧要分片：OS_MBUF_PKTLEN 不能超过 COC_SDU_MTU，
                     * 这里 3950B > COC_SDU_MTU(4096) 没问题，但 mbuf 块可能要扩。 */
                    if (os_mbuf_append(tx, ack, ack_len) != 0) append_ok = false;
                    if (append_ok) {
                        int rc = ble_l2cap_send(event->receive.chan, tx);
                        ESP_LOGI(TAG, "L2CAP TX ack#%u %uB rc=%d",
                                 s_coc_rx_seq, (unsigned)ack_len, rc);
                        if (rc) os_mbuf_free_chain(tx);
                    } else { os_mbuf_free_chain(tx); ESP_LOGE(TAG, "ack append fail"); }
                }
            }
            if (!is_hello) s_coc_rx_seq++;
        }
        coc_recv_ready(event->receive.chan);
        break;
    }
    case BLE_L2CAP_EVENT_COC_DISCONNECTED:
        ESP_LOGI(TAG, "L2CAP COC disconnected (rx total=%luB)",
                 (unsigned long)s_coc_rx_bytes);
        s_coc_chan = NULL;
        s_coc_rx_seq = 0;
        break;
    default: break;
    }
    return 0;
}
static void coc_init(void)
{
    int rc = os_mempool_init(&s_coc_pool, COC_BUF_COUNT, COC_SDU_MTU,
                             s_coc_mem, "coc_sdu_pool");
    if (rc) { ESP_LOGE(TAG, "coc mempool init rc=%d", rc); return; }
    rc = os_mbuf_pool_init(&s_coc_mbuf_pool, &s_coc_pool, COC_SDU_MTU, COC_BUF_COUNT);
    if (rc) { ESP_LOGE(TAG, "coc mbuf pool init rc=%d", rc); return; }
    ESP_LOGI(TAG, "L2CAP CoC pool ready (%d x %dB)", COC_BUF_COUNT, COC_SDU_MTU);
}
static void coc_connect(void)
{
    uint16_t conn = gatt_miot_conn_handle();
    if (conn == BLE_HS_CONN_HANDLE_NONE || s_coc_chan) return;
    struct os_mbuf *m = coc_alloc_sdu();
    if (!m) { ESP_LOGE(TAG, "coc alloc fail"); return; }
    int rc = ble_l2cap_connect(conn, 0x0080, COC_SDU_MTU, m, coc_event_cb, NULL);
    if (rc) { ESP_LOGE(TAG, "ble_l2cap_connect psm=0x80 rc=%d", rc); os_mbuf_free_chain(m); }
    else ESP_LOGI(TAG, "ble_l2cap_connect psm=0x80 sent (conn=%u)", conn);
}
#endif /* COC */

void app_main(void)
{
    esp_err_t err = nvs_flash_init();
    if (err == ESP_ERR_NVS_NO_FREE_PAGES || err == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        nvs_flash_erase(); nvs_flash_init();
    }
#if USE_CUSTOM_MAC
    { uint8_t base[6] = { 0x10, 0x00, 0x3B, 0xCE, BASE_MAC_B4, BASE_MAC_B5 }; esp_base_mac_addr_set(base); }
#endif

    gpio_config_t io = { .pin_bit_mask = 1ULL << BOOT_PIN, .mode = GPIO_MODE_INPUT,
                         .pull_up_en = GPIO_PULLUP_ENABLE };
    gpio_config(&io);
    xTaskCreate(btn_task, "btn", 3072, NULL, 3, NULL);
    xTaskCreate(cli_task, "cli", 4096, NULL, 3, NULL);

    uint8_t mac[6];
    esp_read_mac(mac, ESP_MAC_BT);
    for (int i = 0; i < 6; i++) s_mac_air[i] = mac[5 - i];

    miot_port_esp32_crypto_init();
    fcnt_load();
#if CONFIG_BT_NIMBLE_L2CAP_COC_MAX_NUM >= 1
    coc_init();
#endif

    ESP_LOGI(TAG, "===== 米家口袋照片打印机Pro（xiaomi.printer.ricott / 0x%04X）=====", PRINTER_PID);
    ESP_LOGI(TAG, "串口 state 0-3 / fault 0-3 / batt N / info / factory");

    memset(&s_port, 0, sizeof(s_port));
    s_port.send_notify = gatt_miot_notify_spec;
    s_port.time_now    = port_time_now;
    s_port.random      = port_random;
    s_port.log         = port_log;

    miot_device_init(&s_dev, &s_port);
    miot_device_attach(&s_dev, c_props, sizeof(c_props) / sizeof(c_props[0]),
                       printer_get, printer_set, NULL);
    ESP_LOGI(TAG, "spec 属性 %u 条", (unsigned)(sizeof(c_props) / sizeof(c_props[0])));

    miot_auth_port_t ap;
    memset(&ap, 0, sizeof(ap));
    ap.notify_0010 = gatt_miot_notify_auth_0010;
    ap.notify_0019 = gatt_miot_notify_auth_0019;
    ap.save = id_save; ap.load = id_load; ap.random = port_random;
    miot_auth_init(&s_auth, &ap);

    uint32_t t0 = now_ms();
    miot_auth_prepare(&s_auth);
    ESP_LOGI(TAG, "ECDH 预生成 %lums", (unsigned long)(now_ms() - t0));

    if (nimble_port_init() != ESP_OK) { ESP_LOGE(TAG, "蓝牙初始化失败"); return; }
    esp_log_level_set("NimBLE", ESP_LOG_WARN);
    ble_hs_cfg.sync_cb = on_sync; ble_hs_cfg.reset_cb = NULL;
    ble_svc_gap_init(); ble_svc_gatt_init();
    ble_svc_gap_device_name_set(PRINTER_NAME);
    gatt_miot_register_svcs();
    gatt_miot_bind(&s_auth, &s_dev);
    gatt_miot_set_pid(PRINTER_PID);
    ble_att_set_preferred_mtu(247);

    nimble_port_freertos_init(host_task);

    uint32_t last_adv = 0;
    for (;;) {
        uint32_t t = now_ms();
        miot_auth_poll(&s_auth, t);

        if (s_auth.logged_in && !s_logged_in) {
            s_logged_in = 1;
            miot_device_set_session_keys(&s_dev, miot_auth_session_keys(&s_auth));
            ESP_LOGI(TAG, "*** 会话建立 ***");
            miot_device_send_version_reply(&s_dev, s_dev.tid++);
            /* 全属性初值（2.2 string 单独 push，避免整帧因 STRING 编码超长失败） */
            static miot_spec_value_t v[7];
            memset(v, 0, sizeof(v));
            int i = 0;
            v[i].siid=2; v[i].piid=1; v[i].type=MIOT_TYPE_U8;   v[i++].val.u8=v_state;
            v[i].siid=2; v[i].piid=3; v[i].type=MIOT_TYPE_U8;   v[i++].val.u8=v_copies;
            v[i].siid=2; v[i].piid=4; v[i].type=MIOT_TYPE_BOOL; v[i++].val.u8=v_paper;
            v[i].siid=2; v[i].piid=5; v[i].type=MIOT_TYPE_BOOL; v[i++].val.u8=v_cover;
            v[i].siid=2; v[i].piid=6; v[i].type=MIOT_TYPE_U8;   v[i++].val.u8=v_fault;
            v[i].siid=2; v[i].piid=7; v[i].type=MIOT_TYPE_U16;  v[i++].val.u16=v_timeset;
            v[i].siid=3; v[i].piid=1; v[i].type=MIOT_TYPE_U8;   v[i++].val.u8=v_battery;
            miot_device_send_props_changed(&s_dev, v, (size_t)i);
            ESP_LOGI(TAG, "initial props pushed (%d)", i);
#if CONFIG_BT_NIMBLE_L2CAP_COC_MAX_NUM >= 1
            /* ★真机打印时序：BLE 连接后设备主动连手机 PSM 0x80 的 L2CAP 通道，
             * 手机随后把 55aa 标签/图片帧发下来。这里在会话建立后发起建连。 */
            coc_connect();
#endif
        }

        {
            uint8_t siid = s_dirty_siid;
            uint16_t piid = s_dirty_piid;
            if (piid) { s_dirty_siid = 0; s_dirty_piid = 0; push_prop(siid, piid); }
        }

        if (s_auth.bound != s_was_bound) {
            s_was_bound = s_auth.bound;
            ESP_LOGI(TAG, "*** %s ***", s_was_bound ? "绑定成功" : "绑定清除");
            build_frame(); adv_refresh();
        }

        if (s_ev_left > 0 && (int32_t)(t - last_adv) >= EVENT_GAP_MS) {
            last_adv = t; s_ev_left--; s_fcnt++;
            if (build_frame() >= 0) adv_refresh();
        } else if (!gatt_miot_is_connected() && s_ev_left <= 0 && t - last_adv >= ADV_PERIOD_MS) {
            last_adv = t; s_fcnt++;
            if ((s_fcnt % 10) == 0) fcnt_save();
            s_idx = (s_idx + 1) % FRAME_SLOTS;
            if (build_frame() >= 0) adv_refresh();
            ESP_LOGI(TAG, "broadcast %s", k_names[s_idx]);
        }
        vTaskDelay(pdMS_TO_TICKS(50));
    }
}
